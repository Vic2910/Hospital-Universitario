import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const contract = JSON.parse(readFileSync(new URL('HospitalUniversitario/HospitalUniversitario/Shared/contract.json', root)));
let swift = '// Generated by node scripts/generate-models.mjs. Edit Shared/contract.json.\nimport Foundation\n\n';
for (const [name, fields] of Object.entries(contract.models)) {
  swift += `struct ${name}: Codable, Identifiable, Equatable {\n`;
  for (const [field, type] of Object.entries(fields)) swift += `    let ${field}: ${type}\n`;
  swift += '}\n\n';
}
const destination = new URL('HospitalUniversitario/HospitalUniversitario/Core/Models.generated.swift', root);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== swift) throw new Error('Models are out of sync. Run node scripts/generate-models.mjs');
} else {
  writeFileSync(destination, swift);
  console.log(fileURLToPath(destination));
}
